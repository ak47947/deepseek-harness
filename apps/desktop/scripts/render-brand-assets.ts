/** Generate shell and browser brand derivatives from the transparent ribbon master. */
import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'
import { packIco } from './render-tray-icon.ts'
import { readDesktopConfiguration } from '../src/desktop-configuration.ts'

const root = fileURLToPath(new URL('../../../', import.meta.url))
const source = resolve(root, 'apps/desktop/resources/enterprise/mark.png')
const output = (path: string, content: string | Buffer) => writeFile(resolve(root, path), content)

async function main(): Promise<void> {
  const artwork = await readFile(source)
  const uriFull = `data:image/png;base64,${artwork.toString('base64')}`
  const tile = (inset: number, edge: number) => Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024"><rect x="${inset}" y="${inset}" width="${edge}" height="${edge}" rx="${edge * 0.22}" fill="#fff"/><image x="${inset}" y="${inset}" width="${edge}" height="${edge}" href="${uriFull}"/></svg>`)
  const desktop = await sharp(tile(0, 1024)).png().toBuffer()
  const dock = await sharp(tile(102, 820)).png().toBuffer()
  await output('apps/desktop/resources/enterprise/icon.png', desktop)
  await output('apps/desktop/resources/enterprise/icon-windows.png', desktop)
  await output('apps/desktop/resources/enterprise/icon-macos.png', dock)
  const windows = await Promise.all([16, 24, 32, 48, 64, 128, 256].map(async size => ({
    size, png: await sharp(desktop).resize(size, size).png().toBuffer(),
  })))
  await output('apps/desktop/resources/enterprise/icon.ico', packIco(windows))
  const macSizes = [['icp4', 16], ['icp5', 32], ['icp6', 64], ['ic07', 128], ['ic08', 256], ['ic09', 512], ['ic10', 1024]] as const
  const macChunks = await Promise.all(macSizes.map(async ([type, size]) => {
    const png = await sharp(dock).resize(size, size).png().toBuffer()
    const header = Buffer.alloc(8)
    header.write(type, 0, 'ascii')
    header.writeUInt32BE(png.length + 8, 4)
    return Buffer.concat([header, png])
  }))
  const macHeader = Buffer.alloc(8)
  macHeader.write('icns', 0, 'ascii')
  macHeader.writeUInt32BE(8 + macChunks.reduce((total, chunk) => total + chunk.length, 0), 4)
  await output('apps/desktop/resources/enterprise/icon.icns', Buffer.concat([macHeader, ...macChunks]))
  const compact = await sharp(artwork).resize(128, 128).png().toBuffer()
  await output('packages/client/ui-settings-enterprise-account/src/client/assets/mark.png', compact)
  await output('apps/desktop/renderer/assets/enterprise-mark.png', compact)
  const encoded = Array.from(compact.toString('base64').matchAll(/.{1,100}/gu), match => match[0])
  await output('backend/src/authorization-brand.ts', [
    '/** Generated by apps/desktop/scripts/render-brand-assets.ts from the enterprise ribbon master. */',
    '/** Transparent enterprise mark served by the standalone browser authorization pages. */',
    'export const authorizationBrandPng = Buffer.from(',
    encoded.map(part => `  '${part}'`).join(' +\n') + ',',
    "  'base64',",
    ')',
    '',
  ].join('\n'))
  await output('apps/desktop/resources/enterprise/tray-windows.ico', packIco(await Promise.all([16, 20, 24, 32, 40, 48, 64].map(async size => ({
    size, png: await sharp(artwork).resize(size, size).png().toBuffer(),
  })))))
  const productName = readDesktopConfiguration({ appRoot: resolve(root, 'apps/desktop'), development: true }).productName
    .replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;')
  for (const dark of [false, true]) {
    const name = `<svg xmlns="http://www.w3.org/2000/svg" width="203" height="31" viewBox="0 0 203 31"><text x="101.5" y="25" text-anchor="middle" font-family="Arial, sans-serif" font-size="28" fill="${dark ? '#f5f5f5' : '#0f1115'}">${productName}</text></svg>`
    for (const scale of [1, 2]) {
      const panel = await sharp({ create: { width: 600 * scale, height: 196 * scale, channels: 4, background: '#00000000' } })
        .composite([
          { input: await sharp(artwork).resize(120 * scale).png().toBuffer(), left: 240 * scale, top: 16 * scale },
          { input: await sharp(Buffer.from(name), { density: 72 * scale }).png().toBuffer(), left: 199 * scale, top: 160 * scale },
        ]).png().toBuffer()
      await output(`apps/desktop/installer/assets/enterprise/brand${dark ? '-dark' : ''}${scale === 2 ? '-2x' : ''}.png`, panel)
    }
  }
  const sidebar = await sharp({ create: { width: 164, height: 314, channels: 3, background: '#f3f4f6' } })
    .composite([{ input: await sharp(artwork).resize(120, 120).png().toBuffer(), left: 22, top: 89 }]).png().toBuffer()
  await output('apps/desktop/installer/assets/enterprise/uninstaller-sidebar.png', sidebar)
  console.info('brand assets: wrote desktop, browser, welcome, and installer artwork')
}

if (process.argv[1] !== undefined && import.meta.filename === resolve(process.argv[1])) await main()
